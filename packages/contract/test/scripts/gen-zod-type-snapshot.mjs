#!/usr/bin/env node
// Regenerates test/fixtures/zod-types.snapshot.ts: the z.input and z.output type of every
// zod schema the contract's entry exports (S1-6, RIGG-02).
//
// The first snapshot was taken from the classic-zod contract, before the move to zod/mini.
// A later, deliberate change to a type regenerates it:
//
//   pnpm --filter @avel/contract build
//   node packages/contract/test/scripts/gen-zod-type-snapshot.mjs
//
// How it works: the schema names come from the built entry (dist/index.js: every export that
// is a zod schema, i.e. carries `_zod`). A probe file declares, for each name, one constant
// whose type is `input<typeof Schema>` and one for `output<typeof Schema>`, and tsc's
// declaration emit writes each type out expanded, as plain TypeScript. That text is the
// snapshot. The test never compares text: it compiles the snapshot against the live
// contract and checks the types are equal in both directions (zod-mini-types.test.ts).
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, "..", "..");
const repoRoot = resolve(pkgRoot, "..", "..");
// The built declarations (dist/index.d.ts), so tsc has no source file to emit beside.
const entry = join(pkgRoot, "dist", "index.js");
const out = join(pkgRoot, "test", "fixtures", "zod-types.snapshot.ts");

const built = await import(pathToFileURL(join(pkgRoot, "dist", "index.js")).href);
const names = Object.entries(built)
  .filter(([, v]) => typeof v === "object" && v !== null && "_zod" in v)
  .map(([k]) => k)
  .sort();

// The probe sits inside the package so `zod/v4/core` resolves the way the contract's own imports do.
const dir = mkdtempSync(join(here, ".gen-"));
try {
  const probe = [
    `import type { input, output } from "zod/v4/core";`,
    `import type * as C from ${JSON.stringify(entry)};`,
    // The type is read back through a call, so declaration emit prints what the checker
    // resolved (expanded), not the alias as written here.
    `declare function resolved<T>(): T extends infer U ? U : never;`,
    ...names.flatMap((n) => [
      `export const ${n}__input = resolved<input<typeof C.${n}>>();`,
      `export const ${n}__output = resolved<output<typeof C.${n}>>();`,
    ]),
  ].join("\n");
  writeFileSync(join(dir, "probe.ts"), `${probe}\n`);
  writeFileSync(
    join(dir, "tsconfig.json"),
    JSON.stringify({
      extends: join(repoRoot, "tsconfig.base.json"),
      compilerOptions: {
        declaration: true,
        emitDeclarationOnly: true,
        declarationMap: false,
        sourceMap: false,
        outDir: join(dir, "out"),
        rootDir: dir,
        typeRoots: [join(repoRoot, "node_modules", "@types")],
      },
      files: ["probe.ts"],
    }),
  );
  const tsc = spawnSync(
    join(repoRoot, "node_modules", ".bin", "tsc"),
    ["-p", join(dir, "tsconfig.json")],
    {
      encoding: "utf8",
    },
  );
  const emitted = join(dir, "out", "probe.d.ts");
  let text;
  try {
    text = readFileSync(emitted, "utf8");
  } catch {
    console.error(`tsc emitted no declarations:\n${tsc.stdout}${tsc.stderr}`);
    process.exit(1);
  }
  // Drop the probe's own imports: the snapshot must not depend on the contract it checks.
  const body = text
    .split("\n")
    .filter(
      (l) => !l.startsWith("import type * as C") && !l.startsWith("import type { input, output }"),
    )
    .join("\n");
  const header = [
    "// GENERATED by test/scripts/gen-zod-type-snapshot.mjs. Do not edit by hand.",
    `// z.input and z.output of the ${names.length} zod schemas @avel/contract's entry exports,`,
    "// taken from the classic-zod contract before the move to zod/mini (decisions.md S1-6).",
    `// SCHEMA_COUNT=${names.length}`,
    "",
  ].join("\n");
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, header + body);
  // Format it the way the repo's lint expects, so a regenerated file passes `pnpm lint`.
  spawnSync(join(repoRoot, "node_modules", ".bin", "biome"), ["format", "--write", out], {
    cwd: repoRoot,
    encoding: "utf8",
  });
  console.log(`wrote ${out}: ${names.length} schemas, ${names.length * 2} types`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
