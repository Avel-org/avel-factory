// Writes src/minified.ts from the built router (T-B11 D, CR-W30). Run after `pnpm build`:
// node scripts/generate-minified.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { contract } from "../dist/index.js";

const entries = [];
const walk = (node, keyPath) => {
  if (typeof node !== "object" || node === null) return;
  const def = node["~orpc"];
  if (def && typeof def === "object" && "route" in def) {
    entries.push({
      keyPath,
      method: def.route.method,
      path: def.route.path,
      routeNo: def.meta.routeNo,
      write: def.meta.write,
      stepUp: def.meta.stepUp,
    });
    return;
  }
  for (const [key, child] of Object.entries(node)) walk(child, [...keyPath, key]);
};
walk(contract, []);

const lines = entries.map((e) =>
  [
    "  {",
    `    keyPath: [${e.keyPath.map((k) => JSON.stringify(k)).join(", ")}],`,
    `    method: ${JSON.stringify(e.method)},`,
    `    path: ${JSON.stringify(e.path)},`,
    `    routeNo: ${JSON.stringify(e.routeNo)},`,
    `    write: ${e.write},`,
    `    stepUp: ${e.stepUp},`,
    "  },",
  ].join("\n"),
);
const source = `// Generated by scripts/generate-minified.mjs from the router. Do not edit.
// Every route's key path, method, path, route number, write and stepUp, and no schema.

export interface MinifiedRoute {
  keyPath: readonly string[];
  method: string;
  path: string;
  routeNo: number | null;
  write: boolean;
  stepUp: boolean;
}

export const minifiedRouter: readonly MinifiedRoute[] = [
${lines.join("\n")}
];
`;
writeFileSync(fileURLToPath(new URL("../src/minified.ts", import.meta.url)), source);
